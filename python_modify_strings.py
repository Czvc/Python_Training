# Python has a set of built-in methods that you can use on strings.

# Here are some examples of how to use these string methods.
# 1. Convert a string to uppercase
my_string = "hello world"
upper_string = my_string.upper()
print("Uppercase:", upper_string)

# 2. Convert a string to lowercase
lower_string = my_string.lower()
print("Lowercase:", lower_string)

# 3. Remove whitespace from the beginning and end of a string
whitespace_string = "   Hello World   "
trimmed_string = whitespace_string.strip()
print("Trimmed:", trimmed_string)

# 4. Replace a substring with another substring
replaced_string = my_string.replace("world", "there")
print("Replaced:", replaced_string)

# 5. Split a string into a list of substrings
split_string = my_string.split(" ")
print("Split:", split_string)


